"""Write figures/stats.tex (manuscript macros) from one saved fit seed.

Usage:
    python scripts/export_stats.py [--seed N]
"""

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config.defaults import (
    DEFAULT_DT, EVALUATION_STEPS, MODEL_VERSION, NETWORKS, PLOT_STEPS, PRACTICE_OBJECT, STATES, THOUGHTSEEDS,
)
from experiments.training_pipeline import ROBUSTNESS_SEEDS, SEED, result_path
from viz.analysis_utils import (compute_network_profiles, compute_tail_statistics, regime_belief_accuracy,
                                validate_network_schema)
from viz.ignition import access_summary, anatomy_seed, return_effort_summary, return_effort_training


OUT = ROOT / "figures" / "stats.tex"


def _load(phenotype: str, seed: int) -> dict:
    with result_path(phenotype, seed).open() as handle:
        run = json.load(handle)
    validate_network_schema(run, NETWORKS)
    return run


def _macro(name: str, value: str) -> str:
    return rf"\newcommand{{\{name}}}{{{value}}}"


def _camel(name: str) -> str:
    return "".join(part.title() for part in name.split("_"))


def _f(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def main(seed: int = SEED) -> None:
    results = {name: _load(name, seed) for name in ("expert", "novice")}
    (fit_seed,) = {run["seed"] for run in results.values()}
    lines = [
        "% Auto-generated by scripts/export_stats.py; do not edit by hand.",
        f"% Source: training_results_{{expert,novice}}_seed{fit_seed}.json.",
        f"% Model version: {MODEL_VERSION}.",
        _macro("StatsModelVersion", MODEL_VERSION),
        _macro("StatsSeed", str(fit_seed)),
        _macro("StatsPlotSteps", f"{PLOT_STEPS:,}"),
        _macro("StatsEvaluationSteps", f"{EVALUATION_STEPS:,}"),
        _macro("StatsInitialWindowSteps", f"{EVALUATION_STEPS - PLOT_STEPS:,}"),
        # Fig. 6's run (same rule as viz.report).
        _macro("StatsAnatomySeed", str(anatomy_seed(
            fit_seed, ROBUSTNESS_SEEDS, lambda s: (_load("expert", s), _load("novice", s)),
        ))),
    ]

    for phenotype, run in results.items():
        prefix = phenotype.title()
        profiles = compute_network_profiles(run, STATES, NETWORKS, PLOT_STEPS)
        tail = compute_tail_statistics(run, STATES, PLOT_STEPS)
        for state in STATES:
            state_macro = _camel(state)
            dwell = tail["dwell_times"][state]
            lines.append(_macro(
                f"{prefix}Dwell{state_macro}", '--' if dwell is None else _f(DEFAULT_DT * dwell, 1),
            ))
            for network in NETWORKS:
                net_macro = network.upper()
                lines.append(_macro(
                    f"{prefix}{state_macro}{net_macro}", _f(profiles[state][network]),
                ))
            for destination, probability in tail["transition_matrix"][state].items():
                if destination != state:
                    dest_macro = _camel(destination)
                    lines.append(_macro(
                        f"{prefix}Transition{state_macro}To{dest_macro}", _f(probability, 2),
                    ))

        access = access_summary(run, PLOT_STEPS)
        effort = return_effort_summary(run, PLOT_STEPS)['return_effort_nats']
        lines.append(_macro(f'{prefix}ReturnEffort', '--' if effort is None else _f(effort)))
        breath_prior = run["access_prior"][THOUGHTSEEDS.index(PRACTICE_OBJECT)]
        lines.append(_macro(f'{prefix}LearnedHabitReturn', _f(run['return_habit']['redirect_attention'])))
        training = return_effort_training(run, PLOT_STEPS)
        for tag, value in (('FitFirst', training['first_block_nats']), ('FitLast', training['last_block_nats'])):
            lines.append(_macro(f'{prefix}ReturnEffort{tag}', '--' if value is None else _f(value)))
        lines.extend([
            _macro(f"{prefix}PracticeSteps", f"{int(run['training_steps']):,}"),
            _macro(f"{prefix}AccessEvents", str(int(access["access_onsets"]))),
            _macro(f"{prefix}BreathAccessPercent", _f(access["breath_access_percent"], 1)),
            _macro(f"{prefix}BreathRunSeconds", _f(access["breath_run_seconds"], 1)),
            _macro(f"{prefix}DistractorAccessMWPercent", _f(access["distractor_access_mw_percent"], 1)),
            _macro(f"{prefix}ClarityBF", _f(access["clarity_bf"], 2)),
            _macro(f"{prefix}ClaritySession", _f(access["clarity_session"], 2)),
            _macro(f"{prefix}BreathAccessPrior", _f(breath_prior, 2)),
            _macro(f"{prefix}ObservationPrecision", f"{run['observation_precision']:.0f}"),
            _macro(f"{prefix}RestingClarity", _f(run["resting_clarity"], 2)),
            _macro(f"{prefix}RegimeBeliefPercent", _f(regime_belief_accuracy(run), 1)),
        ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Export manuscript statistics for one saved fit seed.")
    parser.add_argument("--seed", type=int, default=SEED,
                        help=f"fit seed to export (default: {SEED})")
    main(parser.parse_args().seed)
